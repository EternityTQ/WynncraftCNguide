<template>
  <div class="wynn-tree-wrapper">
    <div class="tree-scroll-container">
      
      <div class="tree-content" :style="containerStyle">
        
        <svg class="connections-layer">
          <path 
            v-for="(pathD, index) in connectorPaths" 
            :key="index"
            :d="pathD" 
            class="connector-line"
          />
        </svg>

        <div class="skill-grid" :style="gridStyle">
          <SkillNode 
            v-for="(item, index) in combinedItems" 
            :key="`item-${index}`" 
            :name="item.display_name"
            :current-class="currentClass" 
            :style="getItemStyle(item)"
          />
        </div>
      
      </div>
    </div>
  </div>
</template>

<script>
import SkillNode from './SkillNode.vue'; 
import atreeData from './data/atree.json'; 
import connectorData from './data/connectors.json'; 

export default {
  components: { SkillNode },
  props: {
    // 【修改】通过 Props 接收职业，不再自己管理
    currentClass: {
      type: String,
      default: 'Archer'
    }
  },
  data() {
    return {
      // ...
      // 【修改】这里控制整体大小！
      // 如果想撑满，可以改大到 60 或 65
      // 如果想保持紧凑但去除留白，请看下面的 CSS 修改
      gridCellSize: 60, 
      gridGap: 0,       
    };
  },
  computed: {
    // 1. 获取原始技能数据
    rawSkills() {
      return atreeData[this.currentClass] || [];
    },

    skills() {
      // 仅仅做深拷贝，防止污染源数据，不再修改 row
      return this.rawSkills.map(skill => JSON.parse(JSON.stringify(skill)));
    },

    // 2. 自动生成连接线数据
    autoGeneratedConnectors() {
      const connectionMap = new Map(); // key: "row,col", value: {up, down, left, right}

      // 遍历所有技能节点
      this.skills.forEach(skill => {
        const childRow = skill.display.row;
        const childCol = skill.display.col;

        // 处理每个父节点
        if (skill.parents && skill.parents.length > 0) {
          skill.parents.forEach(parentId => {
            const parent = this.skills.find(s => s.id === parentId);
            if (!parent) return;

            const parentRow = parent.display.row;
            const parentCol = parent.display.col;

            // 如果父子节点相邻（row差1）且在同一列，直接连接，无需连接符
            if (childRow === parentRow + 1 && childCol === parentCol) {
              return;
            }

            // 路径策略：从子节点向上移动，遇到需要水平移动的位置后水平移动到父节点列，然后继续向上
            // 水平移动发生在父节点所在行

            const minCol = Math.min(parentCol, childCol);
            const maxCol = Math.max(parentCol, childCol);

            // 步骤1：垂直连接 - 从子节点上方到父节点行+1（不包括父节点行）
            for (let r = childRow - 1; r > parentRow; r--) {
              this.addConnection(connectionMap, r, childCol, 'up', 'down');
            }

            // 步骤2：在父节点行上进行水平连接（如果需要）
            if (parentCol !== childCol) {
              // 需要水平移动
              for (let c = minCol + 1; c < maxCol; c++) {
                // 水平线段：中间所有格子都是左右连接（排除父节点和子节点位置）
                this.addConnection(connectionMap, parentRow, c, 'left', 'right');
              }

              // 拐角处理
              if (childRow > parentRow + 1) {
                // 有垂直段 + 水平段，需要拐角
                // 拐角在 (parentRow, childCol) 位置，但要确保不是节点位置
                if (parentCol < childCol) {
                  // 父在左，子在右：在 (parentRow, childCol) 产生"左下"拐角
                  this.addConnection(connectionMap, parentRow, childCol, 'down', 'left');
                } else {
                  // 父在右，子在左：在 (parentRow, childCol) 产生"右下"拐角
                  this.addConnection(connectionMap, parentRow, childCol, 'down', 'right');
                }
              } else {
                // 父子相邻行，只有水平移动
                // 在子节点正上方 (parentRow, childCol) 需要水平和向下的连接
                // 但这个位置就是 parentRow，所以不会和子节点冲突
                if (parentCol < childCol) {
                  this.addConnection(connectionMap, parentRow, childCol, 'left', 'down');
                } else {
                  this.addConnection(connectionMap, parentRow, childCol, 'right', 'down');
                }
              }

              // 父节点位置的连接会被过滤掉，所以这里标记是安全的
              if (parentCol === minCol) {
                this.addConnection(connectionMap, parentRow, parentCol, 'down', 'right');
              } else {
                this.addConnection(connectionMap, parentRow, parentCol, 'down', 'left');
              }
            } else {
              // 父子同列，只需垂直连接
              // 父节点位置的连接会被过滤掉
              if (childRow > parentRow + 1) {
                this.addConnection(connectionMap, parentRow, parentCol, 'down', 'up');
              }
            }
          });
        }
      });

      // 将 connectionMap 转换为连接符数组
      return this.convertConnectionMapToConnectors(connectionMap);
    },

    // 3. 处理连线数据：可以选择使用手动数据或自动生成数据
    connectorItems() {
      // 使用自动生成的连接线
      return this.autoGeneratedConnectors;

      // 如果想使用手动数据，可以注释上面一行，取消注释下面的代码：
      /*
      const classConnectors = connectorData[this.currentClass];
      if (!classConnectors) return [];

      const items = [];

      for (const [type, coords] of Object.entries(classConnectors)) {
        if (Array.isArray(coords)) {
          coords.forEach(pos => {
            items.push({
              display_name: type,
              display: {
                row: pos.row,
                col: pos.col,
                icon: type
              }
            });
          });
        }
