      */
    },

    // 4. 合并数据：技能 + 连线
    combinedItems() {
      return [...this.skills, ...this.connectorItems];
    },

    // 5. 计算网格最大尺寸
    gridDimensions() {
      let maxRow = 0;
      this.combinedItems.forEach(item => {
        if (item.display.row > maxRow) maxRow = item.display.row;
      });
      // 【修改】这里改为 +3，给底部留出更多富余空间，防止图标边缘被切
      return { rows: maxRow + 3, cols: 9 };
    },

    containerStyle() {
      const width = this.gridDimensions.cols * (this.gridCellSize + this.gridGap);
      const height = this.gridDimensions.rows * (this.gridCellSize + this.gridGap);
      return { width: `${width}px`, height: `${height}px` };
    },

    gridStyle() {
      return {
        'grid-template-columns': `repeat(${this.gridDimensions.cols}, ${this.gridCellSize}px)`,
        'grid-template-rows': `repeat(${this.gridDimensions.rows}, ${this.gridCellSize}px)`,
        'gap': `${this.gridGap}px`,
        'width': '100%',
        'height': '100%'
      };
    }
  },
  methods: {
    getItemStyle(item) {
      return {
        gridRow: item.display.row + 1,
        gridColumn: item.display.col + 1
      };
    },

    // 辅助方法：向 connectionMap 添加连接
    addConnection(connectionMap, row, col, ...directions) {
      const key = `${row},${col}`;
      if (!connectionMap.has(key)) {
        connectionMap.set(key, { up: false, down: false, left: false, right: false });
      }
      const conn = connectionMap.get(key);
      directions.forEach(dir => {
        if (dir) conn[dir] = true;
      });
    },

    // 辅助方法：将 connectionMap 转换为连接符数组
    convertConnectionMapToConnectors(connectionMap) {
      const items = [];

      // 创建技能节点位置的集合，用于检查冲突
      const skillPositions = new Set();
      this.skills.forEach(skill => {
        const key = `${skill.display.row},${skill.display.col}`;
        skillPositions.add(key);
      });

      connectionMap.forEach((directions, key) => {
        const [row, col] = key.split(',').map(Number);

        // 如果这个位置已经有技能节点，跳过不生成连接符
        if (skillPositions.has(key)) {
          // 调试日志：显示哪些位置被跳过
          // console.log(`跳过节点位置: row=${row}, col=${col}`);
          return;
        }

        const { up, down, left, right } = directions;

        // 根据四个方向的连接情况决定连接符类型
        let connectorType = null;

        // 统计连接方向数量
        const connectionCount = [up, down, left, right].filter(Boolean).length;

        if (connectionCount === 0) {
          return; // 没有连接，跳过
        } else if (connectionCount === 1) {
          // 单向连接不需要连接符（通常是端点）
          return;
        } else if (connectionCount === 2) {
          // 两个方向
          if (up && down) {
            connectorType = '竖线';
          } else if (left && right) {
            connectorType = '横线';
          } else if (down && right) {
            connectorType = '右下'; // 右下拐角
          } else if (down && left) {
            connectorType = '左下'; // 左下拐角
          } else if (up && right) {
            // 暂时用右下代替（可能需要添加对应图片）
            connectorType = '右下';
          } else if (up && left) {
            // 暂时用左下代替（可能需要添加对应图片）
            connectorType = '左下';
          }
        } else if (connectionCount === 3) {
          // 三个方向：丁字类型
          if (!up) {
            connectorType = '丁字'; // 左下右（没有上）
          } else if (!left) {
            connectorType = '右丁字'; // 上右下（没有左）
          } else if (!right) {
            connectorType = '左丁字'; // 上左下（没有右）
          } else if (!down) {
            // 上左右（没有下）：暂时使用丁字
            connectorType = '丁字';
          }
        } else if (connectionCount === 4) {
          // 四个方向都有
          connectorType = '十字';
        }

        if (connectorType) {
          items.push({
            display_name: connectorType,
            display: {
              row: row,
              col: col,
              icon: connectorType
            }
          });
        }
      });

      return items;
    }
  }
}
</script>

